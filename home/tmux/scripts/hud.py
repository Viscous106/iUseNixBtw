#!/usr/bin/env python3
"""Interactive shortcut HUD for tmux.

The hot path -- cycling with h/l -- contains no shell at all. Every keypress
is served by a pre-generated key table (hud-0 .. hud-N) whose bindings are
plain tmux commands, so a move is one in-process redraw rather than a python
start-up plus three tmux round trips (~57ms, which is what made the old
version feel laggy).

Python runs once, on open: it measures the client, lays out a viewport that
actually fits that width, parks each frame in an @hud_bar_N option and hands
control to the hud-0 table. Chips are a fixed width whether selected or not,
so the bar never reflows as the selection moves.
"""
import os
import subprocess
import sys

OPTIONS = [
    ("Pane L", "C-h", "select-pane -L"),
    ("Pane R", "C-l", "select-pane -R"),
    ("Split H", "\\", "split-window -h"),
    ("Split V", "-", "split-window -v"),
    ("Sess Next", "C-j", "switch-client -n"),
    ("Sess Prev", "C-k", "switch-client -p"),
    ("Git Worktree", "g", "display-popup -E -w 80% -h 80% -d '#{pane_current_path}' '~/.config/hypr/scripts/tmux_worktree.sh'"),
    ("Git Status", "G", "display-popup -E -w 80% -h 60% -d '#{pane_current_path}' 'git status; echo; git log --oneline -10; read -n1'"),
    ("Agent Picker", "a", "display-popup -E -w 70% -h 45% '~/.config/tmux/scripts/agent-state.sh pick'"),
    ("Reload", "r", "source-file ~/.config/tmux/tmux.conf"),
    ("Kill Pane", "x", "kill-pane"),
]

HINT = "h/l move  Ent run  Esc exit"
MARKER_W = 2  # reserved each side for the < / > scroll markers, always, so
              # the chips do not shift when a marker appears or disappears

SEL_FG, SEL_BG = "#11111b", "#a6e3a1"
DIM_FG, DIM_BG, KEY_FG = "#cdd6f4", "#313244", "#f9e2af"
HINT_FG = "#fab387"

TABLES = os.path.expanduser("~/.config/tmux/hud-tables.conf")


def chip_width(name, key):
    return len(name) + len(key) + 3


def chip(name, key, selected):
    if selected:
        return f"#[fg={SEL_FG},bg={SEL_BG},bold] {name} {key} #[default]"
    return f"#[fg={DIM_FG},bg={DIM_BG}] {name} #[fg={KEY_FG}]{key} #[default]"


def viewport(sel, width):
    """Widest run of chips containing sel that fits the client."""
    widths = [chip_width(n, k) for n, k, _ in OPTIONS]
    budget = width - len(HINT) - 2 - 2 * MARKER_W
    lo = hi = sel
    used = widths[sel]
    while True:
        grew = False
        if hi + 1 < len(OPTIONS) and used + 1 + widths[hi + 1] <= budget:
            hi += 1
            used += 1 + widths[hi]
            grew = True
        if lo - 1 >= 0 and used + 1 + widths[lo - 1] <= budget:
            lo -= 1
            used += 1 + widths[lo]
            grew = True
        if not grew:
            return lo, hi


def frame(sel, width):
    lo, hi = viewport(sel, width)
    chips = " ".join(
        chip(name, key, i == sel)
        for i, (name, key, _) in enumerate(OPTIONS)
        if lo <= i <= hi
    )
    left = "<" if lo > 0 else " "
    right = ">" if hi < len(OPTIONS) - 1 else " "
    return (
        f"#[fg={HINT_FG},bold]{left} #[default]{chips}"
        f"#[fg={HINT_FG},bold] {right} #[default] #[fg={HINT_FG}]{HINT}"
    )


def tables_conf():
    """One key table per selection index -- the whole hot path, no shell."""
    lines = [
        "# Generated by scripts/hud.py -- do not edit. One table per HUD index;",
        "# each move is a pure tmux command so cycling has no process start-up.",
    ]
    n = len(OPTIONS)
    for i in range(n):
        prev, nxt = (i - 1) % n, (i + 1) % n
        t = f"hud-{i}"
        for key, dest in (("h", prev), ("C-h", prev), ("Left", prev),
                          ("l", nxt), ("C-l", nxt), ("Right", nxt)):
            lines.append(
                f'bind-key -T {t} {key} '
                f'display-message -d 0 "#{{E:@hud_bar_{dest}}}" '
                rf'\; switch-client -T hud-{dest}'
            )
        lines.append(rf'bind-key -T {t} Enter display-message -d 1 "" \; {OPTIONS[i][2]}')
        lines.append(f'bind-key -T {t} Escape display-message -d 1 ""')
        lines.append(f'bind-key -T {t} q display-message -d 1 ""')
        # anything else leaves the HUD instead of silently staying modal
        lines.append(f'bind-key -T {t} Any display-message -d 1 ""')
    return "\n".join(lines) + "\n"


def client_width():
    res = subprocess.run(["tmux", "display-message", "-p", "#{client_width}"],
                         capture_output=True, text=True)
    try:
        return int(res.stdout.strip())
    except ValueError:
        return 80


def open_hud():
    conf = tables_conf()
    if not os.path.exists(TABLES) or open(TABLES).read() != conf:
        with open(TABLES, "w") as fh:
            fh.write(conf)

    width = client_width()
    args = []
    for i in range(len(OPTIONS)):
        args += ["set-option", "-g", f"@hud_bar_{i}", frame(i, width), ";"]
    args += ["source-file", TABLES, ";"]
    args += ["display-message", "-d", "0", "#{E:@hud_bar_0}", ";"]
    args += ["switch-client", "-T", "hud-0"]
    subprocess.run(["tmux", *args])


cmd = sys.argv[1] if len(sys.argv) > 1 else "open"

if cmd in ("open", "show"):
    open_hud()
elif cmd == "gen":
    with open(TABLES, "w") as fh:
        fh.write(tables_conf())
    print(TABLES)
elif cmd == "close":
    subprocess.run(["tmux", "display-message", "-d", "1", ""])
else:
    sys.exit(f"hud.py: unknown command {cmd!r}")
